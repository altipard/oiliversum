// HTML for ECharts tooltips. ECharts inserts formatter output as HTML, so every
// text that comes from data (country codes/names, series names, news titles) is
// escaped here; only numbers formatted by us and ECharts' own markers stay raw.
import type { BreakdownRow, NewsItem } from '../data/types';
import { countryNameDe } from './countries';
import { escapeHtml, formatDate, formatEurLiter, formatShare, perLiter } from './format';
import { taxShare, type TaxMode } from './table';

/** Map tooltip: price for the tax mode and its split into crude, margin and taxes. */
export function mapTooltipHtml(row: BreakdownRow, price: number | null, tax: TaxMode): string {
  const lines = [
    `<strong>${escapeHtml(countryNameDe(row.country_code))}</strong>`,
    `${tax === 'with' ? 'Preis inkl. Steuern' : 'Preis ohne Steuern'}: <strong>${formatEurLiter(price)}</strong>`,
    `Rohöl (Brent): ${formatEurLiter(perLiter(row.crude_eur_1000l))} (${formatShare(row.crude_share)})`,
    `Marge, Raffinerie, Logistik: ${formatEurLiter(perLiter(row.margin_eur_1000l))}`,
    `Steuern und Abgaben: ${formatEurLiter(perLiter(row.tax_eur_1000l))} (${formatShare(taxShare(row))})`,
  ];
  if (tax === 'without') lines.push(`Preis inkl. Steuern: ${formatEurLiter(perLiter(row.eur_1000l_with_tax))}`);
  return lines.join('<br>');
}

/** Map tooltip for a region without bulletin data. */
export function mapNoDataHtml(code: string): string {
  return `${escapeHtml(countryNameDe(code))}<br>keine Daten`;
}

export interface SeriesValue {
  /** Colour dot generated by ECharts (trusted HTML). */
  marker: string;
  name: string;
  value: number;
}

/** Time series tooltip: one line per series, then headlines of news near that week. */
export function seriesTooltipHtml(date: string, values: readonly SeriesValue[], news: readonly NewsItem[]): string {
  return [
    `<strong>Woche ${formatDate(date)}</strong>`,
    ...values.map((v) => `${v.marker}${escapeHtml(v.name)}: <strong>${formatEurLiter(v.value)}</strong>`),
    ...news.map((n) => `• ${escapeHtml(n.title)}`),
  ].join('<br>');
}
